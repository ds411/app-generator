"""Write traces in the comment syntax of the output file (ADR 0004)."""

from collections.abc import Callable
from pathlib import PurePosixPath
from typing import Any

import jinja2

from appgen.dsl.model import AppDefinition
from appgen.gen.render import GenerationError

TRACE_KINDS = ("generated", "gap", "manual")
TRACE_SCOPES = ("file", "begin", "end")

GENERATED_NOTICE = "Generated by appgen. Do not edit: change the app definition instead."
EXTENSION_NOTICE = "Created by appgen once. appgen never changes or deletes this file."

type CommentStyle = tuple[str, str]
"""The text before and after a one-line comment."""

_HASH: CommentStyle = ("# ", "")
_SLASH: CommentStyle = ("// ", "")
_BLOCK: CommentStyle = ("/* ", " */")
_HTML: CommentStyle = ("<!-- ", " -->")
JSX_STYLE: CommentStyle = ("{/* ", " */}")

# The comment syntax of each file type of ADR 0004, by file extension.
_SUFFIX_STYLES: dict[str, CommentStyle] = {
    ".ts": _SLASH,
    ".mts": _SLASH,
    ".cts": _SLASH,
    ".js": _SLASH,
    ".mjs": _SLASH,
    ".cjs": _SLASH,
    ".tsx": _SLASH,
    ".jsx": _SLASH,
    ".py": _HASH,
    ".pyi": _HASH,
    ".sql": ("-- ", ""),
    ".css": _BLOCK,
    ".dockerfile": _HASH,
    ".yaml": _HASH,
    ".yml": _HASH,
    ".toml": _HASH,
    ".sh": _HASH,
    ".env": _HASH,
    ".md": _HTML,
    ".html": _HTML,
}


def comment_style(path: str) -> CommentStyle | None:
    """Return the comment syntax of a file, or None if the file type has no comments."""
    name = PurePosixPath(path).name
    if name == "Dockerfile" or name.startswith(("Dockerfile.", ".env.")) or name == ".env":
        return _HASH
    return _SUFFIX_STYLES.get(PurePosixPath(name).suffix)


def format_trace(element_id: str, kind: str = "generated", scope: str | None = None) -> str:
    """Return the trace tag for an element, for example `@trace:gap operations.x file`."""
    if kind not in TRACE_KINDS:
        raise GenerationError(f"The trace kind {kind!r} is not known.")
    if scope is not None and scope not in TRACE_SCOPES:
        raise GenerationError(f"The trace scope {scope!r} is not known.")
    tag = "@trace" if kind == "generated" else f"@trace:{kind}"
    return f"{tag} {element_id}" + (f" {scope}" if scope else "")


def trace_globals(definition: AppDefinition) -> dict[str, Callable[..., str]]:
    """Return the Jinja2 helpers `trace` and `trace_header` for a definition.

    The helpers read the output path and the kind of the file from the
    template context, and write the trace in the comment syntax of the
    file. They stop the run for an ID that is not an element of the
    definition, so that the generator never writes an invalid trace.
    """

    def _style(context: jinja2.runtime.Context, jsx: bool) -> CommentStyle:
        path: str = context["output_path"]
        style = comment_style(path)
        if style is None:
            raise GenerationError(
                f"The file '{path}' cannot hold comments. Its traces come from the manifest."
            )
        return JSX_STYLE if jsx else style

    def _check(element_id: str) -> None:
        if definition.find(element_id) is None:
            raise GenerationError(f"The trace refers to '{element_id}', which is not an element.")

    def _default_kind(context: jinja2.runtime.Context) -> str:
        return "gap" if context["output_kind"] == "extension" else "generated"

    @jinja2.pass_context
    def trace(
        context: jinja2.runtime.Context,
        element_id: str,
        scope: str | None = None,
        kind: str | None = None,
        jsx: bool = False,
    ) -> str:
        _check(element_id)
        before, after = _style(context, jsx)
        tag = format_trace(element_id, kind or _default_kind(context), scope)
        return f"{before}{tag}{after}"

    @jinja2.pass_context
    def trace_header(context: jinja2.runtime.Context, *element_ids: str) -> str:
        if not element_ids:
            raise GenerationError("A trace header needs one or more element IDs.")
        before, after = _style(context, jsx=False)
        extension = context["output_kind"] == "extension"
        notice = EXTENSION_NOTICE if extension else GENERATED_NOTICE
        lines = [f"{before}{notice}{after}"]
        for element_id in element_ids:
            _check(element_id)
            tag = format_trace(element_id, _default_kind(context), "file")
            lines.append(f"{before}{tag}{after}")
        return "\n".join(lines)

    helpers: dict[str, Any] = {"trace": trace, "trace_header": trace_header}
    return helpers
