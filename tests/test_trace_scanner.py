from pathlib import Path

import pytest

from appgen.trace import DEFAULT_IGNORE, Trace, comment_openers, scan_folder, scan_text


def _ids(traces: list[Trace]) -> list[str]:
    return [t.element_id for t in traces]


@pytest.mark.parametrize(
    ("path", "text"),
    [
        ("a.ts", "const a = 1; // @trace app\n"),
        ("a.ts", "/* @trace app */\n"),
        ("a.tsx", "return <div>{/* @trace app */}</div>;\n"),
        ("a.py", "x = 1  # @trace app\n"),
        ("a.sql", "id uuid -- @trace app\n"),
        ("a.css", ":root {} /* @trace app */\n"),
        ("Dockerfile", "FROM python # @trace app\n"),
        ("api.dockerfile", "# @trace app\n"),
        ("a.yaml", "db: # @trace app\n"),
        ("a.yml", "db: # @trace app\n"),
        ("a.md", "<!-- @trace app -->\n"),
        ("a.html", "<p></p><!-- @trace app -->\n"),
        ("a.toml", "# @trace app\n"),
        (".env.local", "# @trace app\n"),
    ],
)
def test_finds_traces_in_each_file_type(path: str, text: str) -> None:
    traces, problems = scan_text(text, path)

    assert problems == []
    assert _ids(traces) == ["app"]


def test_trace_has_its_file_line_kind_id_and_scope() -> None:
    text = (
        "// Generated by appgen. Do not edit: change the app definition instead.\n"
        "// @trace entities.Task file\n"
        "\n"
        "export type Task = {\n"
        "  title: string; // @trace entities.Task.fields.title\n"
        "};\n"
    )

    traces, problems = scan_text(text, "src/task.ts")

    assert problems == []
    assert traces == [
        Trace(
            "src/task.ts", 2, 4, "entities.Task", "generated", "file", "@trace entities.Task file"
        ),
        Trace(
            "src/task.ts",
            5,
            21,
            "entities.Task.fields.title",
            "generated",
            "line",
            "@trace entities.Task.fields.title",
        ),
    ]


def test_reads_the_kind() -> None:
    text = (
        "# @trace:gap operations.a file\n# @trace:manual operations.b\nx = 1 # @trace:generated c\n"
    )

    traces, _ = scan_text(text, "a.py")

    assert [(t.element_id, t.kind) for t in traces] == [
        ("operations.a", "gap"),
        ("operations.b", "manual"),
        ("c", "generated"),
    ]


def test_ids_can_have_segments_that_start_with_a_digit() -> None:
    traces, _ = scan_text("--x: 1; /* @trace ui.tokens.color.blue.600 */\n", "a.css")

    assert _ids(traces) == ["ui.tokens.color.blue.600"]


def test_text_after_the_trace_is_not_a_part_of_it() -> None:
    traces, problems = scan_text("x = 1  # @trace app because the app needs it\n", "a.py")

    assert problems == []
    assert traces[0].text == "@trace app"


def test_finds_two_traces_on_one_line() -> None:
    traces, _ = scan_text("a; /* @trace a */ /* @trace b */\n", "a.ts")

    assert _ids(traces) == ["a", "b"]


@pytest.mark.parametrize(
    "text",
    [
        '@trace("x")\ndef f(): ...\n',
        'x = "@trace app"\n',
        "x = 1  # see @trace app\n",
        '"""\n@trace app\n"""\n',
        "x = 1  # @traced app\n",
    ],
)
def test_ignores_tags_that_do_not_follow_a_comment_opener(text: str) -> None:
    assert scan_text(text, "a.py") == ([], [])


def test_ignores_the_later_lines_of_a_block_comment() -> None:
    assert scan_text("/**\n * @trace app\n */\n", "a.ts") == ([], [])


def test_files_of_an_unknown_type_have_no_traces() -> None:
    assert comment_openers("package.json") is None
    assert scan_text("// @trace app\n", "package.json") == ([], [])


@pytest.mark.parametrize(
    ("text", "code"),
    [
        ("# @trace\n", "malformed-trace"),
        ("# @trace:gap\n", "malformed-trace"),
        ("# @trace .app\n", "malformed-trace"),
        ("# @trace:todo app\n", "unknown-kind"),
        ("# @trace app start\n", "unknown-scope"),
        ("# @trace app beginning\n", "unknown-scope"),
    ],
)
def test_reports_malformed_traces(text: str, code: str) -> None:
    traces, problems = scan_text(text, "a.py")

    assert traces == []
    assert [(p.file, p.line, p.column, p.code) for p in problems] == [("a.py", 1, 3, code)]


def test_file_traces_must_be_in_the_header() -> None:
    text = (
        "#!/usr/bin/env python\n"
        "# -*- coding: utf-8 -*-\n"
        "# @trace app file\n"
        "\n"
        "# @trace entities file\n"
        "import os\n"
        "# @trace pages file\n"
    )

    traces, problems = scan_text(text, "a.py")

    assert _ids(traces) == ["app", "entities"]
    assert [(p.line, p.code) for p in problems] == [(7, "file-trace-not-in-header")]


def test_header_can_have_block_comments() -> None:
    text = "/**\n * The task table.\n */\n// @trace app file\n'use client';\n"

    traces, problems = scan_text(text, "a.tsx")

    assert problems == []
    assert _ids(traces) == ["app"]


def test_a_shebang_can_come_before_the_header_of_any_file() -> None:
    traces, problems = scan_text("#!/usr/bin/env node\n// @trace app file\n", "a.js")

    assert problems == []
    assert _ids(traces) == ["app"]


def test_blocks_can_nest() -> None:
    text = (
        "{/* @trace a begin */}\n"
        "{/* @trace a.b begin */}\n"
        "x\n"
        "{/* @trace a.b end */}\n"
        "{/* @trace a end */}\n"
    )

    traces, problems = scan_text(text, "a.tsx")

    assert problems == []
    assert [(t.line, t.scope) for t in traces] == [
        (1, "begin"),
        (2, "begin"),
        (4, "end"),
        (5, "end"),
    ]


def test_reports_block_traces_without_their_other_end() -> None:
    text = "# @trace a end\n# @trace b begin\n"

    traces, problems = scan_text(text, "a.py")

    assert traces == []
    assert [(p.line, p.code) for p in problems] == [(1, "unmatched-end"), (2, "unclosed-block")]


@pytest.mark.parametrize(
    "end",
    ["# @trace b end", "# @trace:manual a end"],
)
def test_reports_an_end_that_does_not_agree_with_the_innermost_block(end: str) -> None:
    traces, problems = scan_text(f"# @trace a begin\n{end}\n", "a.py")

    assert [(t.line, t.scope) for t in traces] == [(1, "begin")]
    assert [(p.line, p.code) for p in problems] == [(2, "mismatched-end")]


def test_reads_crlf_line_endings() -> None:
    traces, problems = scan_text("// @trace app file\r\nx; // @trace a\r\n", "a.ts")

    assert problems == []
    assert [(t.element_id, t.scope) for t in traces] == [("app", "file"), ("a", "line")]


def _write(root: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def test_scans_a_folder(tmp_path: Path) -> None:
    _write(
        tmp_path,
        {
            "b/model.py": "# @trace entities file\n",
            "a/page.tsx": "// @trace pages file\n",
            "a/broken.ts": "// @trace:oops app\n",
            "package.json": '{"x": "// @trace app"}\n',
        },
    )

    result = scan_folder(tmp_path)

    assert result.files == ["a/broken.ts", "a/page.tsx", "b/model.py"]
    assert [str(t) for t in result.traces] == [
        "a/page.tsx:1:4: @trace pages file",
        "b/model.py:1:3: @trace entities file",
    ]
    assert [(p.file, p.line, p.code) for p in result.problems] == [
        ("a/broken.ts", 1, "unknown-kind")
    ]


def test_skips_the_default_ignore_list(tmp_path: Path) -> None:
    _write(
        tmp_path,
        {
            "node_modules/x/index.js": "// @trace app\n",
            "web/node_modules/y.ts": "// @trace app\n",
            ".venv/lib/a.py": "# @trace app\n",
            "src/a.ts": "// @trace app\n",
        },
    )

    assert scan_folder(tmp_path).files == ["src/a.ts"]


def test_skips_a_configured_ignore_list(tmp_path: Path) -> None:
    _write(tmp_path, {"vendor/a.ts": "// @trace app\n", "src/a.ts": "// @trace app\n"})

    result = scan_folder(tmp_path, ignore=[*DEFAULT_IGNORE, "vendor/"])

    assert result.files == ["src/a.ts"]


def test_skips_the_paths_in_gitignore(tmp_path: Path) -> None:
    _write(
        tmp_path,
        {
            ".gitignore": "*.gen.ts\nout/\n!keep.gen.ts\n",
            "web/.gitignore": "/local.ts\n",
            "a.gen.ts": "// @trace app\n",
            "keep.gen.ts": "// @trace app\n",
            "out/a.ts": "// @trace app\n",
            "web/local.ts": "// @trace app\n",
            "web/sub/local.ts": "// @trace app\n",
        },
    )

    assert scan_folder(tmp_path).files == ["keep.gen.ts", "web/sub/local.ts"]
    assert len(scan_folder(tmp_path, use_gitignore=False).files) == 5


def test_skips_binary_files(tmp_path: Path) -> None:
    (tmp_path / "a.ts").write_bytes(b"// @trace app\n\0")

    assert scan_folder(tmp_path).files == []


def test_root_must_be_a_folder(tmp_path: Path) -> None:
    with pytest.raises(NotADirectoryError):
        scan_folder(tmp_path / "missing")
