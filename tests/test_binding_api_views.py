def test_nextjs_calls_the_operation_in_the_server_component_of_the_page(
    nextjs_result: GenerationResult,
) -> None:
    files = _files(nextjs_result)
    route = _route(files, "/books")
    assert 'import { connection } from "next/server";' in route
    assert 'import { booksClient } from "@/shared/api/books";' in route
    assert "  await connection();\n" in route
    assert (
        '  const result = await viewAnswer(() => booksClient().listBooks({ genre: "fiction", '
        "limit: 50 })); // @trace apis.books.operations.listBooks\n"
    ) in route
    assert "  return <BooksPage result={result} />;\n" in route
    page = files["src/pages/books/ui/books-page.tsx"]
    assert "export function BooksPage({ result }: BookTableViewProps) {" in page
    assert "<BookTableView result={result} /> {/* @trace pages.books.content */}" in page
    http = files["src/shared/api/third-party.ts"]
    assert "export async function viewAnswer<T>(call: () => Promise<T>)" in http
    assert "export function useRefresh(): () => void {" in files["src/shared/lib/router.tsx"]


def test_nextjs_gives_the_path_parameters_of_the_page_to_the_operation(
    nextjs_result: GenerationResult,
) -> None:
    files = _files(nextjs_result)
    route = _route(files, "/authors/{author}/{year}/{genre}")
    assert 'PageProps<"/authors/[author]/[year]/[genre]">' in route
    assert "  const route: Record<string, string | undefined> = await params;\n" in route
    assert (
        'booksClient().listAuthorBooks({ author: route.author ?? "", year: Number(route.year '
        '?? ""), genre: (route.genre ?? "") as ListAuthorBooksParams["genre"], signed: true })'
    ) in route
    assert 'import { booksClient, type ListAuthorBooksParams } from "@/shared/api/books";' in route
    view = files["src/widgets/author-books/ui/author-books-view.tsx"]
    # The server calls the operation: the view does not name its params.
    assert "ListAuthorBooksParams" not in view


