def _files(result: GenerationResult) -> dict[str, str]:
    return {f.path: f.content for f in result.files}


def _route(files: dict[str, str], path: str) -> str:
    """Return the route file of the Next.js app for a page path, for example `/books`."""
    folder = re.sub(r"\{([^}]+)\}", r"[\1]", path)
    [found] = [p for p in files if p.startswith("app/") and p.endswith(f"{folder}/page.tsx")]
    return files[found]


