import re
from pathlib import Path

import pytest

from appgen.dsl import AppDefinition, load_definition
from appgen.gen import Binding, GenerationError, Output, find_binding, generate, write_result
from appgen.gen.manifest import read_manifest
from appgen.gen.traces import comment_style, format_trace

TESTS = Path(__file__).parent

# The scanner pattern of ADR 0004.
TRACE = re.compile(
    r"@trace(?::(?P<kind>[a-z]+))?[ \t]+(?P<id>[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*)"
    r"(?:[ \t]+(?P<scope>file|begin|end)\b)?"
)


@pytest.fixture
def definition() -> AppDefinition:
    return load_definition(TESTS / "fixtures" / "project-tracker.yaml")


def _binding(tmp_path: Path, template: str, path: str, *, extension: bool = False) -> Binding:
    (tmp_path / "t.j2").write_text(template)
    return Binding(
        name="temp",
        description="A binding for one test.",
        template_dir=tmp_path,
        outputs=(Output("t.j2", path, "entity", extension=extension),),
        covers=frozenset({"app", "entity"}),
    )


@pytest.mark.parametrize(
    ("path", "line"),
    [
        ("src/task.ts", "// @trace entities.Task"),
        ("src/task.tsx", "// @trace entities.Task"),
        ("app/task.py", "# @trace entities.Task"),
        ("db/0001.sql", "-- @trace entities.Task"),
        ("src/theme.css", "/* @trace entities.Task */"),
        ("Dockerfile", "# @trace entities.Task"),
        ("compose.yaml", "# @trace entities.Task"),
        ("README.md", "<!-- @trace entities.Task -->"),
        (".env.example", "# @trace entities.Task"),
    ],
)
def test_trace_uses_the_comment_syntax_of_the_file(
    tmp_path: Path, definition: AppDefinition, path: str, line: str
) -> None:
    binding = _binding(tmp_path, "{{ trace(element_id) }}", "{{ name }}/" + path)
    task = generate(definition, binding).files[-1]
    assert task.content == line + "\n"


def test_trace_in_jsx_children(tmp_path: Path, definition: AppDefinition) -> None:
    binding = _binding(tmp_path, "{{ trace(element_id, 'begin', jsx=true) }}", "{{ name }}.tsx")
    assert generate(definition, binding).files[0].content == (
        "{/* @trace entities.Project begin */}\n"
    )


def test_trace_header_of_a_generated_file(tmp_path: Path, definition: AppDefinition) -> None:
    binding = _binding(tmp_path, "{{ trace_header(element_id) }}", "{{ name }}.py")
    assert generate(definition, binding).files[0].content == (
        "# Generated by appgen. Do not edit: change the app definition instead.\n"
        "# @trace entities.Project file\n"
    )


def test_trace_header_of_an_extension_file(tmp_path: Path, definition: AppDefinition) -> None:
    binding = _binding(
        tmp_path, "{{ trace_header(element_id) }}", "{{ name }}.ext.ts", extension=True
    )
    assert generate(definition, binding).files[0].content == (
        "// Created by appgen once. appgen never changes or deletes this file.\n"
        "// @trace:gap entities.Project file\n"
    )


def test_a_trace_to_an_unknown_element_stops_the_run(
    tmp_path: Path, definition: AppDefinition
) -> None:
    binding = _binding(tmp_path, "{{ trace('entities.Nothing') }}", "{{ name }}.ts")
    with pytest.raises(GenerationError, match=r"'entities\.Nothing', which is not an element"):
        generate(definition, binding)


def test_a_file_without_a_trace_stops_the_run(tmp_path: Path, definition: AppDefinition) -> None:
    binding = _binding(tmp_path, "export {};", "{{ name }}.ts")
    with pytest.raises(GenerationError, match="with no trace"):
        generate(definition, binding)


def test_a_file_without_comments_gets_its_traces_from_the_manifest(
    tmp_path: Path, definition: AppDefinition
) -> None:
    templates = tmp_path / "templates"
    templates.mkdir()
    binding = _binding(templates, "{}", "{{ name }}.json")
    result = generate(definition, binding)
    assert result.files[0].traces == ("entities.Project",)
    out = tmp_path / "out"
    write_result(result, out, binding.name)
    manifest = read_manifest(out)
    assert manifest is not None
    assert manifest.traces == {
        "Project.json": ("entities.Project",),
        "Task.json": ("entities.Task",),
    }


def test_a_trace_in_a_file_without_comments_stops_the_run(
    tmp_path: Path, definition: AppDefinition
) -> None:
    binding = _binding(tmp_path, "{{ trace(element_id) }}", "{{ name }}.json")
    with pytest.raises(GenerationError, match="cannot hold comments"):
        generate(definition, binding)


def test_format_trace() -> None:
    assert format_trace("app") == "@trace app"
    assert format_trace("app", "manual", "end") == "@trace:manual app end"
    with pytest.raises(GenerationError):
        format_trace("app", "other")
    with pytest.raises(GenerationError):
        format_trace("app", scope="line")


def test_comment_style_of_unknown_types_is_none() -> None:
    assert comment_style("package.json") is None
    assert comment_style("LICENSE") is None


def test_each_minimal_file_has_valid_traces(definition: AppDefinition) -> None:
    for file in generate(definition, find_binding("minimal")).files:
        if comment_style(file.path) is None:
            assert file.traces
            continue
        matches = list(TRACE.finditer(file.content))
        assert matches, file.path
        for match in matches:
            assert match["kind"] in (None, "generated", "gap", "manual")
            assert definition.find(match["id"]) is not None
