"""Tests of the map views (ADR 0046): a marker for each record, and the records of the area."""

import json
from textwrap import dedent

import pytest

from appgen.dsl import load_definition_text, validate_definition
from appgen.dsl.ui.views import MapView
from appgen.gen import find_binding, generate

MAP = dedent(
    """\
    version: 0
    app: { name: sites, title: Sites }
    entities:
      Site:
        crud: { operations: [list, read], views: [detail] }
        display_field: name
        fields:
          name: { type: string, required: true }
          kind: { type: enum, values: [park, view] }
          location: { type: point }
    pages:
      map: { path: /map, title: Map, content: { view: site_map } }
      site: { path: "/sites/{id}", title: Site, entity: Site, content: { view: site_detail } }
    ui:
      views:
        site_map:
          kind: map
          entity: Site
          title: Sites on the map
          point: location
          link: site
          filters:
            kind: { kind: select, field: kind }
            nearby: { kind: near, field: location, distance: 3 }
    """
)
API = MAP.replace(
    "app: { name: sites, title: Sites }", "app: { name: sites, title: Sites, x-react-data: api }"
)


def codes(text: str) -> list[tuple[str, str | None]]:
    definition = load_definition_text(text, "app.yaml")
    return [(d.code, d.element_id) for d in validate_definition(definition)]


def files(text: str, binding: str) -> dict[str, str]:
    result = generate(load_definition_text(text, "app.yaml"), find_binding(binding))
    return {f.path: f.content for f in result.files}


def test_a_map_view_is_valid() -> None:
    assert codes(MAP) == []
    definition = load_definition_text(MAP, "app.yaml")
    view = definition.ui.views["site_map"] if definition.ui else None
    assert isinstance(view, MapView)
    assert (view.point, view.label, view.link) == ("location", None, "site")
    assert list(view.filters) == ["kind", "nearby"]


@pytest.mark.parametrize(
    ("change", "expected"),
    [
        # The point of a map is a point field.
        (("point: location", "point: name"), [("unsuitable-field", "ui.views.site_map")]),
        # A move of the map gives the area: a map view takes no area filter.
        (
            ("kind: { kind: select, field: kind }", "box: { kind: area, field: location }"),
            [("invalid-option", "ui.views.site_map.filters.box")],
        ),
        # A sort needs a value to compare, and a point has two.
        (
            ("link: site", "link: site\n      sort: { field: location }"),
            [("unsuitable-field", "ui.views.site_map.sort")],
        ),
        (("link: site", "link: nowhere"), [("unknown-reference", "ui.views.site_map")]),
    ],
)
def test_a_map_view_needs_a_point_and_no_area_filter(
    change: tuple[str, str], expected: list[tuple[str, str | None]]
) -> None:
    assert codes(MAP.replace(*change)) == expected


def test_the_nextjs_map_reads_the_tiles_of_a_setting() -> None:
    app = files(MAP, "nextjs")
    view = app["src/widgets/site-map/ui/site-map-view.tsx"]
    assert view.startswith("// Generated by appgen.") and "// @trace ui.views.site_map file" in view
    assert "<GeoMap" in view and "onMove={setBox}" in view
    assert "inBox(row.location, box)" in view
    assert 'navigate(pageHref("site", { id: String(row.id) }))' in view
    tiles = app["src/shared/ui/geo-map.tsx"]
    assert "process.env.NEXT_PUBLIC_MAP_TILES || " in tiles
    assert "https://tile.openstreetmap.org/{z}/{x}/{y}.png" in tiles
    assert 'void import("leaflet")' in tiles
    package = json.loads(app["package.json"])
    assert package["dependencies"]["leaflet"] == "1.9.4"
    assert package["devDependencies"]["@types/leaflet"] == "1.9.22"
    assert "## Maps" in app["README.md"]
    assert "NEXT_PUBLIC_MAP_TILES=" in app[".env.example"]
    assert "ARG NEXT_PUBLIC_MAP_TILES" in app["Dockerfile"]


def test_the_react_map_filters_its_records_in_the_browser() -> None:
    app = files(MAP, "react")
    view = app["src/widgets/site-map/ui/site-map-view.tsx"]
    assert "rows.filter((row) => inBox(row.location, box))" in view
    assert "isNear(row.location, filters.nearby)" in view
    assert "import.meta.env.VITE_MAP_TILES" in app["src/shared/ui/geo-map.tsx"]
    assert "readonly VITE_MAP_TILES?: string;" in app["src/vite-env.d.ts"]
    assert "ARG VITE_MAP_TILES" in app["Dockerfile"]


def test_the_react_map_of_the_api_loads_the_records_of_its_area() -> None:
    view = files(API, "react")["src/widgets/site-map/ui/site-map-view.tsx"]
    assert (
        'siteApi.all({ ...params, "location_area": box ? boxText(box) : null }, VIEW_SORT)' in view
    )
    assert "location_near: nearParam(filters.nearby)," in view
    assert "useResource(JSON.stringify([query, box])" in view


def test_the_fastapi_list_endpoint_takes_the_area_of_the_map() -> None:
    query = files(API, "fastapi")["app/features/sites/list_sites.py"]
    assert "    # @trace ui.views.site_map\n    location_area: BoxText | None = Field(" in query
    assert "    # @trace ui.views.site_map.filters.nearby\n    location_near: PointText" in query
