ROOT = Path(__file__).parent.parent
EXAMPLE = ROOT / "examples" / "room-booking" / "app.yaml"

BASE = dedent(
    """\
    version: 0
    app: { name: tracker, title: Tracker }
    entities:
      Person:
        fields:
          email: { type: email, required: true, unique: true }
    pages:
      people: { path: /people, title: People }
    auth:
      user_entity: Person
      username_field: email
      password_reset: {}
      delivery: smtp
    """
)


def codes(text: str) -> list[tuple[str, str | None]]:
    definition = load_definition_text(text, "app.yaml")
    return [(d.code, d.element_id) for d in validate_definition(definition)]


def files(binding: Binding, text: str | None = None) -> dict[str, str]:
    definition = load_definition_text(text, "app.yaml") if text else load_definition(EXAMPLE)
    return {f.path: f.content for f in generate(definition, binding).files}


def knative_files(binding: Binding) -> dict[str, str]:
    """Return the files of the room booking example with both deployment targets."""
    key = f"x-{binding.name}-deploy"
    text = EXAMPLE.read_text().replace("app:\n", f"app:\n  {key}: [kubernetes, knative]\n", 1)
    return files(binding, text)


def test_the_delivery_is_the_extension_file_by_default() -> None:
    definition = load_definition_text(BASE, "app.yaml")
    assert validate_definition(definition) == []
    assert definition.auth is not None and definition.auth.delivery == "smtp"
    without = load_definition_text(BASE.replace("  delivery: smtp\n", ""), "app.yaml")
    assert without.auth is not None and without.auth.delivery == "extension"
    with pytest.raises(DefinitionError, match="'extension' or 'smtp'"):
        load_definition_text(BASE.replace("delivery: smtp", "delivery: post"), "app.yaml")


def test_the_delivery_by_smtp_needs_an_email_field_for_the_address() -> None:
    text = BASE.replace("type: email, required", "type: string, required")
    assert codes(text) == [("unsuitable-field", "auth")]
    assert codes(text.replace("  delivery: smtp\n", "")) == []


def test_the_fastapi_app_sends_the_messages_with_smtplib_in_a_thread() -> None:
    app = files(fastapi.BINDING)
    assert "app/core/messages_ext.py" not in app
    assert "from app.core.mail import deliver_message\n" in app["app/core/auth.py"]
    mail = app["app/core/mail.py"]
    assert mail.startswith("# Generated by appgen")
    assert "# @trace auth.password_reset file\n" in mail
    assert "# @trace auth.sign_up.verify_email file\n" in mail
    assert "    await asyncio.to_thread(send_email, settings, email)\n" in mail
    deliver = '    if not await deliver_email(settings, email, "the messages of the sign-in"):\n'
    assert deliver in mail
    config = app["app/core/config.py"]
    assert '    smtp_tls: Literal["starttls", "tls", "none"] = "starttls"\n' in config
    assert "SMTP_HOST=\n" in app[".env.example"]
    assert "SMTP_HOST=smtp.example.com\n" in app["deploy/kubernetes/config.env"]
    assert "SMTP_PASSWORD=\n" in app["deploy/kubernetes/secret.example.env"]
    assert "def test_a_message_goes_to_the_smtp_server(" in app["tests/test_mail.py"]
    knative = knative_files(fastapi.BINDING)["deploy/knative/service.yaml"]
    assert "name: room-booking-smtp-password" in knative


def test_without_messages_the_fastapi_app_has_no_mail_module() -> None:
    text = BASE.replace("  password_reset: {}\n", "")
    app = files(fastapi.BINDING, text)
    assert "app/core/mail.py" not in app
    assert "app/core/messages_ext.py" not in app
    assert "SMTP_HOST" not in app[".env.example"]


def test_the_nextjs_app_sends_the_messages_with_nodemailer() -> None:
    app = files(nextjs.BINDING)
    assert "src/shared/auth/messages.ext.ts" not in app
    for path in ("src/shared/auth/actions.ts", "src/shared/auth/email-verification.ts"):
        assert 'import { deliverMessage } from "./mail";\n' in app[path]
    mail = app["src/shared/auth/mail.ts"]
    assert mail.startswith("// Generated by appgen")
    assert "// @trace auth.password_reset file\n" in mail
    send = "transport.sendMail({ from, to: email.to, subject: email.subject, text: email.text });"
    assert send in mail
    assert 'if (!(await sendEmail(message, "the messages of the sign-in"))) {' in mail
    package = json.loads(app["package.json"])
    assert package["dependencies"]["nodemailer"] == SMTP_PACKAGES["nodemailer"]
    assert "SMTP_HOST=\n" in app[".env.example"]
    assert "      SMTP_HOST: ${SMTP_HOST:-}\n" in app["compose.yaml"]
    assert "SMTP_HOST=smtp.example.com\n" in app["deploy/kubernetes/config.env"]
    assert "SMTP_PASSWORD=\n" in app["deploy/kubernetes/secret.example.env"]
    knative = knative_files(nextjs.BINDING)["deploy/knative/service.yaml"]
    assert "name: room-booking-web-smtp-password" in knative
    hook = files(nextjs.BINDING, EXAMPLE.read_text().replace("  delivery: smtp\n", ""))
    assert "nodemailer" not in json.loads(hook["package.json"])["dependencies"]
    assert "src/shared/auth/mail.ts" not in hook


@pytest.mark.parametrize("binding", ["fastapi", "nextjs"])
def test_the_check_reports_no_gap_of_the_delivery(tmp_path: Path, binding: str) -> None:
    runner = CliRunner()
    generated = runner.invoke(app, ["generate", str(EXAMPLE), "-b", binding, "-o", str(tmp_path)])
    assert generated.exit_code == 0, generated.output
    result = runner.invoke(app, ["check", str(EXAMPLE), str(tmp_path), "-f", "json"])
    gaps = {g["id"] for g in json.loads(result.output)["gaps"]}
    assert not {"auth.password_reset", "auth.sign_up.verify_email"} & gaps


def mock_smtp() -> ModuleType:
    """Load `scripts/mock_smtp.py`: the folder `scripts` is not a package."""
    spec = importlib.util.spec_from_file_location("mock_smtp", ROOT / "scripts" / "mock_smtp.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_the_mock_smtp_server_keeps_each_message(tmp_path: Path) -> None:
    out = tmp_path / "messages.jsonl"
    out.write_text("an old line\n")
    email = EmailMessage()
    email["From"], email["To"], email["Subject"] = "app@example.com", "a@example.com", "Hello"
    email.set_content("Open the link:\n\n.http://localhost/a?token=x\n")
    with mock_smtp().serving(port=0, out=out) as mailbox:
        with smtplib.SMTP("127.0.0.1", mailbox.port, timeout=10) as client:
            client.send_message(email)
        assert len(mailbox.messages) == 1
    (line,) = out.read_text().splitlines()
    message = json.loads(line)
    assert message["to"] == ["a@example.com"]
    assert message["subject"] == "Hello"
    # The dot at the start of a line comes back.
    assert message["text"] == "Open the link:\n\n.http://localhost/a?token=x\n"
