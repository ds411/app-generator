"""Check the schema change flow of the FastAPI app (ADR 0009) on a database with data.

The script copies a generated FastAPI app of the project tracker into a
temporary folder, and then:

1. applies the first migration to a SQLite database, and adds a record,
2. generates the app again from a changed definition (a new field), into
   the same folder,
3. makes the next migration with `alembic revision --autogenerate`, and
   applies it,
4. checks that the record stays, that the new column exists, that the
   first migration did not change, that the models and the migrations
   agree (`alembic check`), and that `appgen check` passes.

Then it does the same steps for the verification of the email address
(ADR 0023) and the second factor (ADR 0024): it generates
`tests/fixtures/account-security.yaml` without `verify_email` and
`second_factor`, adds a user with a password, turns both on, and checks
that the next migration keeps the user verified, with the second factor
off.

`scripts/check-fastapi.sh` runs it after its other checks. Run it by hand
from the repository root, with a generated app:

    uv run scripts/check_schema_change.py <app folder>

The script needs uv. It uses no Docker, no port, and no shared file.
"""

import os
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

DEFINITION = Path("examples/project-tracker/app.yaml")
SECURITY = Path("tests/fixtures/account-security.yaml")
VERIFY_EMAIL = "    verify_email: { token_minutes: 120 }\n"
SECOND_FACTOR = "  second_factor:\n    totp: true\n    required_roles: [admin]\n"
FIRST = Path("migrations/versions/0001_schema.py")
PERSON = "    fields:\n      name: { type: string, required: true, max_length: 120 }\n"
NEW_FIELD = "      phone: { type: string, max_length: 40 }\n"


class SchemaChangeError(Exception):
    """A check of the schema change failed."""


def log(message: str) -> None:
    print(f"schema-change: {message}", flush=True)


def run(args: list[str], cwd: Path, env: dict[str, str] | None = None) -> None:
    subprocess.run(args, cwd=cwd, env=env, check=True)


def changed_definition(folder: Path) -> Path:
    """Write the project tracker with the new field `phone` of Person, and return its path."""
    text = DEFINITION.read_text()
    if text.count(PERSON) < 1:
        raise SchemaChangeError(f"{DEFINITION} has no fields of Person in the expected form.")
    # The other files of the example, for example the OpenAPI documents of its APIs.
    shutil.copytree(DEFINITION.parent, folder, dirs_exist_ok=True)
    path = folder / "app.yaml"
    path.write_text(text.replace(PERSON, PERSON + NEW_FIELD, 1))
    return path


def check(app: Path) -> None:
    root = Path.cwd()
    with tempfile.TemporaryDirectory(prefix="appgen-schema-change.") as temp:
        work = Path(temp) / "app"
        shutil.copytree(app, work, ignore=shutil.ignore_patterns(".venv", "*.db", "__pycache__"))
        database = Path(temp) / "data.db"
        # The generated app has its own virtual environment.
        env = {k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}
        env["DATABASE_URL"] = f"sqlite+aiosqlite:///{database}"
        log("uv sync")
        run(["uv", "sync", "--quiet"], work, env)

        log("apply the first migration, and add a person")
        run(["uv", "run", "alembic", "upgrade", "head"], work, env)
        person = uuid.uuid4()
        with sqlite3.connect(database) as connection:
            connection.execute(
                "INSERT INTO people (id, name, email, role, active) VALUES (?, ?, ?, ?, ?)",
                (person.hex, "Ada Lovelace", "ada@example.com", "lead", 1),
            )
        first = (work / FIRST).read_bytes()

        log("generate the app again with the new field Person.phone")
        definition = changed_definition(Path(temp))
        args = ["uv", "run", "--locked", "appgen", "generate", str(definition), "-b", "fastapi"]
        run([*args, "-o", str(work)], root)
        if (work / FIRST).read_bytes() != first:
            raise SchemaChangeError(f"The new run changed {FIRST}.")

        log("alembic revision --autogenerate")
        message = "add the phone of a person"
        run(["uv", "run", "alembic", "revision", "--autogenerate", "-m", message], work, env)
        new = [p for p in (work / FIRST.parent).glob("*.py") if p.name != FIRST.name]
        if len(new) != 1 or "phone" not in new[0].read_text():
            raise SchemaChangeError("The autogenerated migration does not add the column phone.")
        log(f"alembic upgrade head ({new[0].name})")
        run(["uv", "run", "alembic", "upgrade", "head"], work, env)
        run(["uv", "run", "alembic", "check"], work, env)

        with sqlite3.connect(database) as connection:
            columns = {row[1] for row in connection.execute("PRAGMA table_info(people)")}
            rows = connection.execute(
                "SELECT name, phone FROM people WHERE id = ?", (person.hex,)
            ).fetchall()
        if "phone" not in columns:
            raise SchemaChangeError("The table people has no column phone.")
        if rows != [("Ada Lovelace", None)]:
            raise SchemaChangeError(f"The person did not stay: {rows}.")

        log("appgen check")
        run(["uv", "run", "--locked", "appgen", "check", str(definition), str(work)], root)
    log("passed")


def check_account_security(root: Path) -> None:
    """Turn on `verify_email` and `second_factor` in an app with a user.

    The user stays verified (ADR 0023), and its second factor is off (ADR 0024).
    """
    with tempfile.TemporaryDirectory(prefix="appgen-schema-change.") as temp:
        text = SECURITY.read_text()
        for part in (VERIFY_EMAIL, SECOND_FACTOR):
            if part not in text:
                raise SchemaChangeError(f"{SECURITY} has no {part.strip()!r}.")
        before = Path(temp) / "before.yaml"
        before.write_text(text.replace(VERIFY_EMAIL, "").replace(SECOND_FACTOR, ""))
        work = Path(temp) / "app"
        args = ["uv", "run", "--locked", "appgen", "generate"]
        log(f"generate {SECURITY} without verify_email and second_factor")
        run([*args, str(before), "-b", "fastapi", "-o", str(work)], root)
        database = Path(temp) / "data.db"
        env = {k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}
        env["DATABASE_URL"] = f"sqlite+aiosqlite:///{database}"
        run(["uv", "sync", "--quiet"], work, env)
        run(["uv", "run", "alembic", "upgrade", "head"], work, env)
        member = uuid.uuid4()
        with sqlite3.connect(database) as connection:
            connection.execute(
                "INSERT INTO members (id, login, email, name, role) VALUES (?, ?, ?, ?, ?)",
                (member.hex, "ada", "ada@example.com", "Ada Lovelace", "admin"),
            )
            connection.execute(
                "INSERT INTO credentials (user_id, password_hash) VALUES (?, ?)",
                (member.hex, "scrypt$00$00"),
            )

        log("generate the app again with verify_email and second_factor")
        run([*args, str(SECURITY), "-b", "fastapi", "-o", str(work)], root)
        message = "verify the email addresses, and add the second factor"
        run(["uv", "run", "alembic", "revision", "--autogenerate", "-m", message], work, env)
        new = [p for p in (work / FIRST.parent).glob("*.py") if p.name != FIRST.name]
        for column in ("email_verified_at", "totp_secret", "totp_failures", "recovery_codes"):
            if len(new) != 1 or column not in new[0].read_text():
                raise SchemaChangeError(f"The migration does not add the column {column}.")
        run(["uv", "run", "alembic", "upgrade", "head"], work, env)
        run(["uv", "run", "alembic", "check"], work, env)
        with sqlite3.connect(database) as connection:
            rows = connection.execute(
                "SELECT email_verified_at, totp_enabled_at, totp_failures FROM credentials"
                " WHERE user_id = ?",
                (member.hex,),
            ).fetchall()
        if len(rows) != 1 or rows[0][0] is None:
            raise SchemaChangeError(f"The user that exists is not verified: {rows}.")
        if rows[0][1:] != (None, 0):
            raise SchemaChangeError(f"The second factor of the user that exists is on: {rows}.")
    log("passed: the users that exist are verified, with the second factor off")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        check(Path(sys.argv[1]).resolve())
        check_account_security(Path.cwd())
    except (SchemaChangeError, subprocess.CalledProcessError) as error:
        print(f"schema-change: failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
